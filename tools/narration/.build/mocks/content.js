export function getDayContent(day) {
    const idx = Math.max(0, Math.min(day - 1, DAYS.length - 1));
    const d = DAYS[idx];
    const triad = [];
    const phases = [
        { key: 'thank', label: 'Thank & Praise', sc: d.thank, pr: d.thankPrompt },
        { key: 'repent', label: 'Repent & Forgive', sc: d.repent, pr: d.repentPrompt },
        { key: 'invite', label: 'Invite Holy Spirit', sc: d.invite, pr: d.invitePrompt },
        { key: 'ask', label: 'Ask & Receive', sc: d.ask, pr: d.askPrompt },
        { key: 'declare', label: 'Declare', sc: d.declare, pr: d.declarePrompt },
    ];
    for (const p of phases) {
        if (p.sc) {
            triad.push({ label: p.label, text: p.sc });
        }
        else if (p.pr) {
            triad.push({ label: p.label, text: p.pr });
        }
    }
    return {
        day: idx + 1,
        title: d.title,
        phase: d.subtitle,
        settle: d.settle,
        teach: d.focus,
        triad,
        silence: {
            durationSeconds: d.silence * 60,
            prompt: d.silenceTxt,
        },
        act: d.act,
        identity: d.identity,
        verse: d.verse,
        declare: d.declare || undefined,
    };
}
export function getHtmlDay(day) {
    const idx = Math.max(0, Math.min(day - 1, DAYS.length - 1));
    return DAYS[idx];
}
export function getPhaseLabel(day) {
    if (day <= 7)
        return 'Fully Scripted';
    if (day <= 14)
        return 'Partially Guided';
    if (day <= 21)
        return 'Minimal Scripting';
    return 'You Lead';
}
export function getPhaseInstruction(day) {
    if (day <= 7)
        return 'Read each prayer aloud slowly';
    if (day <= 14)
        return 'Use the prompts to find your words';
    if (day <= 21)
        return 'Minimal guidance — your voice leads';
    return 'No script. Just you and God.';
}
export function isScriptedDay(day) {
    return day <= 7;
}
