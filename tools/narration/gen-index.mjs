#!/usr/bin/env node
/**
 * gen-index.mjs — generate expo/services/narrationIndex.ts from the
 * canonical bake manifest (tools/narration/manifest.json).
 *
 * The app resolves baked audio two ways (see services/narration.ts):
 *  - BY_HASH: sha256(`${voice}|${speed}|${text}`) → file, for every
 *    single-text unit (voiceover, narration, declare-button, declaration).
 *    The runtime recomputes the hash of the exact text it is about to
 *    speak; a hit means that text was baked.
 *  - SELAH_LOOPS: content key (`{track}/d{NN}/selah`) → assembled loop
 *    file, for the Night Selah sleep loop.
 *
 * Re-run after every bake:  node tools/narration/gen-index.mjs
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const MANIFEST = path.join(HERE, 'manifest.json');
const OUT = path.resolve(HERE, '..', '..', 'expo', 'services', 'narrationIndex.ts');

const manifest = JSON.parse(await readFile(MANIFEST, 'utf8'));

const byHash = new Map();
let collisions = 0;
for (const unit of Object.values(manifest.units)) {
  if (byHash.has(unit.hash)) {
    // Same voice+speed+text rendered to two paths — the audio is identical
    // by construction, so either path is correct; keep the first.
    collisions += 1;
    continue;
  }
  byHash.set(unit.hash, unit.file);
}

const selahLoops = new Map();
for (const [key, group] of Object.entries(manifest.selahGroups)) {
  selahLoops.set(key, group.file);
}

const entries = (map) =>
  [...map.entries()]
    .sort(([a], [b]) => (a < b ? -1 : 1))
    .map(([k, v]) => `  '${k}': '${v}',`)
    .join('\n');

const out = `/**
 * GENERATED by tools/narration/gen-index.mjs from tools/narration/manifest.json
 * (bake voice ${manifest.voice}, generated ${manifest.generatedAt}).
 * Do not edit by hand — re-run the generator after a re-bake.
 *
 * BAKED_BY_HASH: sha256 of \`voice|speed|text\` → Storage path in the
 * public \`narration\` bucket. SELAH_LOOPS: content key → loop file.
 */
export const BAKED_BY_HASH: Record<string, string> = {
${entries(byHash)}
};

export const SELAH_LOOPS: Record<string, string> = {
${entries(selahLoops)}
};
`;

await writeFile(OUT, out);
console.log(`wrote ${OUT}`);
console.log(`units indexed by hash: ${byHash.size} (hash collisions folded: ${collisions})`);
console.log(`selah loops indexed: ${selahLoops.size}`);
